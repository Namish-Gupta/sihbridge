// Helper historical timeline points
const generateHistory = (baseVal: number, baseline: number, variance: number, points = 24, isAi = false) => {
    const result = [];
    const now = new Date();
    for (let i = points - 1; i >= 0; i--) {
        const time = new Date(now.getTime() - i * 3600 * 1000 * 2);
        // Add realistic upward drift for the last few points
        const drift = i < 6 ? (6 - i) * (variance * 0.4) : 0;
        const noise = (Math.sin(i * 0.7) + (Math.random() - 0.5) * 0.3) * variance;
        const val = Number((baseVal + noise + drift).toFixed(1));
        const item: any = {
            timestamp: time.toISOString().substring(11, 16),
            value: val,
            baseline: baseline,
        };
        if (isAi) {
            item.uncertaintyUpper = Number((val + Math.abs(val * 0.04)).toFixed(1));
            item.uncertaintyLower = Number((val - Math.abs(val * 0.04)).toFixed(1));
        }
        result.push(item);
    }
    return result;
};

